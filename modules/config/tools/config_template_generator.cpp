#include <config/config.h>

#include <fstream>
#include <iostream>
#include <map>
#include <string>

// 配置模板生成器
class ConfigTemplateGenerator
{
public:
    void addSection(const std::string &name, const std::string &description = "")
    {
        sections_.push_back({name, description, {}});
        currentSection_ = &sections_.back();
    }

    void addField(const std::string &key, const std::string &defaultValue,
                  const std::string &description = "", const std::string &type = "")
    {
        if (!currentSection_) {
            std::cerr << "Error: No section created. Call addSection() first.\n";
            return;
        }
        currentSection_->fields.push_back({key, defaultValue, description, type});
    }

    bool generate(const std::string &filename) const
    {
        std::ofstream out(filename);
        if (!out) {
            std::cerr << "Failed to create file: " << filename << '\n';
            return false;
        }

        out << "# NovaInfra Configuration File\n";
        out << "# Generated by config template generator\n";
        out << "# Edit this file to customize your configuration\n\n";

        for (const auto &section : sections_) {
            if (!section.description.empty()) {
                out << "# " << section.description << "\n";
            }
            out << "[" << section.name << "]\n";

            for (const auto &field : section.fields) {
                if (!field.description.empty()) {
                    out << "# " << field.description;
                    if (!field.type.empty()) {
                        out << " (type: " << field.type << ")";
                    }
                    out << "\n";
                }
                out << field.key << " = " << field.defaultValue << "\n";
                out << "\n";
            }
            out << "\n";
        }

        out.close();
        if (!out) {
            std::cerr << "Failed to write file: " << filename << '\n';
            return false;
        }
        std::cout << "Configuration template generated: " << filename << '\n';
        return true;
    }

    bool generateWithComments(const std::string &filename, bool allCommented = false) const
    {
        std::ofstream out(filename);
        if (!out) {
            std::cerr << "Failed to create file: " << filename << '\n';
            return false;
        }

        out << "# NovaInfra Configuration File\n";
        out << "# Generated by config template generator\n";
        out << "# Uncomment and edit values as needed\n\n";

        for (const auto &section : sections_) {
            if (!section.description.empty()) {
                out << "# " << section.description << "\n";
            }
            out << "[" << section.name << "]\n";

            for (const auto &field : section.fields) {
                if (!field.description.empty()) {
                    out << "# " << field.description;
                    if (!field.type.empty()) {
                        out << " (type: " << field.type << ")";
                    }
                    out << "\n";
                }
                if (allCommented) {
                    out << "# ";
                }
                out << field.key << " = " << field.defaultValue << "\n";
                out << "\n";
            }
            out << "\n";
        }

        out.close();
        if (!out) {
            std::cerr << "Failed to write file: " << filename << '\n';
            return false;
        }
        std::cout << "Configuration template generated: " << filename << '\n';
        return true;
    }

private:
    struct Field {
        std::string key;
        std::string defaultValue;
        std::string description;
        std::string type;
    };

    struct Section {
        std::string name;
        std::string description;
        std::vector<Field> fields;
    };

    std::vector<Section> sections_;
    Section *currentSection_ = nullptr;
};

bool generateWebServerTemplate()
{
    ConfigTemplateGenerator gen;

    gen.addSection("server", "Web server configuration");
    gen.addField("host", "\"127.0.0.1\"", "Server bind address", "string");
    gen.addField("port", "8080", "Server port number (1-65535)", "integer");
    gen.addField("max_connections", "1000", "Maximum concurrent connections", "integer");
    gen.addField("timeout_ms", "30000", "Request timeout in milliseconds", "integer");
    gen.addField("enable_tls", "false", "Enable TLS/HTTPS", "boolean");

    gen.addSection("server.tls", "TLS/HTTPS configuration");
    gen.addField("cert_file", "\"/path/to/cert.pem\"", "TLS certificate file path", "string");
    gen.addField("key_file", "\"/path/to/key.pem\"", "TLS private key file path", "string");
    gen.addField("min_version", "\"TLSv1.2\"", "Minimum TLS version", "string");

    gen.addSection("database", "Database configuration");
    gen.addField("url", "\"postgresql://localhost/mydb\"", "Database connection URL", "string");
    gen.addField("max_pool_size", "20", "Maximum connection pool size", "integer");
    gen.addField("min_pool_size", "5", "Minimum connection pool size", "integer");
    gen.addField("connection_timeout_ms", "5000", "Connection timeout in milliseconds", "integer");

    gen.addSection("logging", "Logging configuration");
    gen.addField("level", "\"info\"", "Log level: trace, debug, info, warning, error, critical", "string");
    gen.addField("file", "\"/var/log/myapp.log\"", "Log file path (empty for stdout)", "string");
    gen.addField("max_file_size_mb", "100", "Maximum log file size in MB", "integer");
    gen.addField("max_files", "10", "Maximum number of log files to keep", "integer");

    gen.addSection("cache", "Cache configuration");
    gen.addField("enabled", "true", "Enable caching", "boolean");
    gen.addField("max_size_mb", "1024", "Maximum cache size in MB", "integer");
    gen.addField("ttl_seconds", "3600", "Default cache entry TTL in seconds", "integer");

    return gen.generate("config.webserver.toml") &&
           gen.generateWithComments("config.webserver.example.toml", true);
}

bool generateDatabaseServiceTemplate()
{
    ConfigTemplateGenerator gen;

    gen.addSection("service", "Service configuration");
    gen.addField("name", "\"database-service\"", "Service name", "string");
    gen.addField("host", "\"0.0.0.0\"", "Service bind address", "string");
    gen.addField("port", "5432", "Service port", "integer");
    gen.addField("workers", "4", "Number of worker threads", "integer");

    gen.addSection("database", "Database configuration");
    gen.addField("engine", "\"postgresql\"", "Database engine: postgresql, mysql, sqlite", "string");
    gen.addField("host", "\"localhost\"", "Database host", "string");
    gen.addField("port", "5432", "Database port", "integer");
    gen.addField("database", "\"mydb\"", "Database name", "string");
    gen.addField("username", "\"user\"", "Database username", "string");
    gen.addField("password", "\"password\"", "Database password (use env var in production!)", "string");

    gen.addSection("pool", "Connection pool configuration");
    gen.addField("min_connections", "5", "Minimum pool size", "integer");
    gen.addField("max_connections", "50", "Maximum pool size", "integer");
    gen.addField("idle_timeout_seconds", "600", "Connection idle timeout", "integer");

    gen.addSection("monitoring", "Monitoring and metrics");
    gen.addField("enabled", "true", "Enable monitoring", "boolean");
    gen.addField("metrics_port", "9090", "Metrics HTTP port", "integer");
    gen.addField("health_check_interval_seconds", "30", "Health check interval", "integer");

    return gen.generate("config.database-service.toml") &&
           gen.generateWithComments("config.database-service.example.toml", true);
}

int main(int argc, char *argv[])
{
    std::cout << "NovaInfra Config Template Generator\n";
    std::cout << "===================================\n\n";

    if (argc < 2) {
        std::cout << "Usage: " << argv[0] << " <template-type>\n\n";
        std::cout << "Available templates:\n";
        std::cout << "  webserver        - Web server configuration template\n";
        std::cout << "  database-service - Database service configuration template\n";
        std::cout << "  all              - Generate all templates\n";
        return 1;
    }

    std::string templateType = argv[1];

    if (templateType == "webserver") {
        if (!generateWebServerTemplate())
            return 1;
    } else if (templateType == "database-service") {
        if (!generateDatabaseServiceTemplate())
            return 1;
    } else if (templateType == "all") {
        if (!generateWebServerTemplate())
            return 1;
        if (!generateDatabaseServiceTemplate())
            return 1;
    } else {
        std::cerr << "Unknown template type: " << templateType << '\n';
        return 1;
    }

    std::cout << "\nTemplate generation complete!\n";
    return 0;
}
